// Builds the FIPS 203 ML-KEM-768 Rust core for wasm32 and embeds it in the SDK
// as base64. Run `npm run build:mlkem` after changing anything under pqc/.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pqcDir = join(here, '..', '..', 'pqc');
const wasmPath = join(
  pqcDir,
  'target',
  'wasm32-unknown-unknown',
  'release',
  'peervault_mlkem768.wasm'
);

execFileSync(
  'cargo',
  ['build', '--release', '--target', 'wasm32-unknown-unknown'],
  { cwd: pqcDir, stdio: 'inherit' }
);

const wasm = readFileSync(wasmPath);
const base64 = wasm.toString('base64');
const output = `// Auto-generated by scripts/build-mlkem.mjs. Do not edit by hand.
// FIPS 203 ML-KEM-768 core compiled to wasm32-unknown-unknown (${wasm.byteLength} bytes).
export const MLKEM768_WASM_BASE64 =
  '${base64}';
`;

writeFileSync(join(here, '..', 'src', 'mlkem-wasm.generated.ts'), output);
console.log(`embedded ML-KEM-768 wasm: ${wasm.byteLength} bytes`);
